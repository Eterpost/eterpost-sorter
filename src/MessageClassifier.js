const MessageTypes = require('./MessageTypes');


class MessageClassifier {
  constructor (unsubscribeAdditionalAddress) {
    this.unsubscribeAdditionalAddress = unsubscribeAdditionalAddress;
  }

  classifyMessage (message) {
    if (this._isUnsubscribe(message)) {
      return MessageTypes.UNSUBSCRIBE;
    }

    if (this._isMailServer(message)) {
      return MessageTypes.MAIL_SERVER;
    }

    if (this._isAutoresponder(message)) {
      return MessageTypes.AUTORESPONDER;
    }

    return MessageTypes.HUMAN;
  }

  _isAutoresponder (message) {
    const autoSubmittedValue = message.headers.get('auto-submitted');
    const isAutoSubmitted = !(autoSubmittedValue === undefined || autoSubmittedValue === 'no');

    const xAutoreply = message.headers.get('x-autoreply');
    const hasXAutoreply = xAutoreply && xAutoreply.toLowerCase() === 'yes';

    const xAutogenerated = message.headers.get('x-autogenerated');
    const hasXAutogenerated = xAutogenerated && xAutogenerated.toLowerCase() === 'reply';
    if (isAutoSubmitted || hasXAutoreply || hasXAutogenerated) {
      return true;
    }

    const subject = message.headers.get('subject');

    if (subject && subject.toLowerCase().indexOf('autoreply') !== -1) {
      return true;
    }

    return false;
  }

  _isMailServer (message) {
    const contentType = message.headers.get('content-type');
    if (contentType && typeof contentType.value === 'string' &&
        contentType.value.trim() === 'multipart/report') {
      return true;
    }

    if (message.headers.has('x-mailer-daemon-error') ||
        message.headers.has('x-failed-recipients') ||
        message.headers.has('x-mailer-daemon-recipients')) {
      return true;
    }

    return false;
  }

  // Адрес вида <user>+unsubscribe или <user>+unsubscribe-<номер рассылки>
  _parseUnsubscribe (message) {
    const username = message.toAddress.split('@')[0];
    const tag = username.split('+')[1];
    if (typeof tag !== 'string') {
      return;
    }
    const word = String(this.unsubscribeAdditionalAddress).toLowerCase();
    const lowerTag = tag.toLowerCase();
    if (lowerTag === word) {
      return { mailingId: undefined };
    }
    const match = lowerTag.startsWith(word + '-') && /^\d+$/.exec(lowerTag.slice(word.length + 1));
    if (match) {
      const mailingId = Number(match[0]);
      if (Number.isSafeInteger(mailingId) && mailingId >= 1) {
        return { mailingId };
      }
    }
  }

  _isUnsubscribe (message) {
    return Boolean(this._parseUnsubscribe(message));
  }

  // Номер рассылки из адреса <user>+unsubscribe-<номер>; без номера — undefined
  getUnsubscribeMailingId (message) {
    const parsed = this._parseUnsubscribe(message);
    return parsed ? parsed.mailingId : undefined;
  }
}

module.exports = MessageClassifier;
